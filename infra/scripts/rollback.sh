#!/usr/bin/env bash
# =============================================================================
# infra/scripts/rollback.sh — repin the previous app:<sha> images (§17.3)
# =============================================================================
# WHAT IT DOES
#   Brings the app tier back onto the PREVIOUS deployed image tag:
#     resolution:  --tag <sha>  >  PREV_IMAGE_TAG env  >  deploy-state file
#   (state is written by deploy-v2.sh into STATE_DIR; the box keeps the
#   previous TWO images, §17.3).
#   Mechanism: each app service's CURRENT image reference (from
#   `docker compose config`) is re-pinned to the previous tag with `docker tag`
#   (local image first, else `docker pull`), then `up -d --no-deps <services>`.
#   This works whether infra/compose interpolates ${IMAGE_TAG} or hardcodes
#   pins — once it interpolates, `IMAGE_TAG=<prev> compose up -d --no-deps …`
#   is the equivalent one-liner.
#   Tag scheme (documented, shared with deploy-v2.sh):
#     ghcr.io/<owner>/<svc>:<git-sha>   — CI tags every main build.
#
# WHAT IT NEVER DOES
#   ✗ The DATABASE is NEVER rolled back automatically. Migrations are
#     FORWARD-ONLY (§4/§12): no down files exist and the drizzle journal
#     (packages/db/migrations) is append-only — never delete journal rows.
#   If the failed deploy MIGRATED and old code truly cannot tolerate the new
#   schema, that is a §17.4 incident — in this order:
#     1. stop writes:
#          docker compose --env-file ../../.env -f ../compose/docker-compose.yml \
#            stop gateway worker engine-pool
#     2. take a safety dump NOW (before anything else):
#          docker compose --env-file ../../.env -f ../compose/docker-compose.yml \
#            exec -T db pg_dump -U "$POSTGRES_USER" -Fc "$POSTGRES_DB" \
#            > pre-rollback-$(date -u +%FT%TZ).dump
#     3. restore the last pre-deploy backup with infra/scripts/restore.sh
#        (RB-06 restore drill, §17.4) — accepting data loss back to RPO (≤ 24 h).
#     4. NEVER hand-edit the schema via psql (§4). Read-only triage is fine:
#          docker compose --env-file ../../.env -f ../compose/docker-compose.yml \
#            exec -T db psql -U "$POSTGRES_USER" -d "$POSTGRES_DB" \
#            -c 'select * from drizzle.__drizzle_migrations order by id;'
#        (journal table as generated by drizzle-kit; packages/db/migrations
#         is the truth — do not edit it)
#
# Usage:
#   infra/scripts/rollback.sh [--tag <sha>] [--yes] [service ...]
#     default services: gateway worker engine-pool web. `db` and `valkey` are
#     REFUSED — their data must never bounce between app versions.
# Env: ENV_FILE, COMPOSE_FILE, PREV_IMAGE_TAG, ROLLBACK_YES=1, HEALTH_TIMEOUT
#      (120s), STATE_DIR (/var/lib/studio-deploy), NO_COLOR.
# Exit: 0 rolled back; 1 usage/pre-flight; 2 tag not resolvable; 3 up/health/smoke.
# =============================================================================
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_DIR="$(cd "$SCRIPT_DIR/../.." && pwd)"
ENV_FILE="${ENV_FILE:-$REPO_DIR/.env}"
COMPOSE_FILE="${COMPOSE_FILE:-$SCRIPT_DIR/../compose/docker-compose.yml}"
STATE_DIR="${STATE_DIR:-/var/lib/studio-deploy}"
STATE_FILE="$STATE_DIR/deploy-state.env"
HISTORY_FILE="$STATE_DIR/tag-history.log"
HEALTH_TIMEOUT="${HEALTH_TIMEOUT:-120}"

compose() { docker compose --env-file "$ENV_FILE" -f "$COMPOSE_FILE" "$@"; }

env_get() {
  grep -m1 -E "^$1=" "$ENV_FILE" 2>/dev/null | cut -d= -f2- \
    | sed -e 's/^"//g' -e 's/"$//g' -e "s/^'//g" -e "s/'\$//g" || true
}

POSTGRES_USER="${POSTGRES_USER:-$(env_get POSTGRES_USER)}"; POSTGRES_USER="${POSTGRES_USER:-studio}"
POSTGRES_DB="${POSTGRES_DB:-$(env_get POSTGRES_DB)}"; POSTGRES_DB="${POSTGRES_DB:-studio}"

# --- colored status output ---------------------------------------------------------
if [ -t 2 ] && [ -z "${NO_COLOR:-}" ]; then
  C_G=$'\033[32m' C_Y=$'\033[33m' C_R=$'\033[31m' C_B=$'\033[34m' C_0=$'\033[0m'
else
  C_G='' C_Y='' C_R='' C_B='' C_0=''
fi
step() { printf '%s %s[rollback]%s %s\n' "$(date -u +%FT%TZ)" "$C_B" "$C_0" "$*" >&2; }
ok()   { printf '    %s✓%s %s\n' "$C_G" "$C_0" "$*" >&2; }
warn() { printf '    %s!%s %s\n' "$C_Y" "$C_0" "$*" >&2; }
err()  { printf '    %s✗%s %s\n' "$C_R" "$C_0" "$*" >&2; }
die()  { err "FATAL: $*"; exit 1; }

usage() {
  cat <<'EOF'
infra/scripts/rollback.sh — repin the previous app:<sha> images (§17.3)
Usage:
  infra/scripts/rollback.sh [--tag <sha>] [--yes] [service ...]
    --tag <sha>   explicit previous tag (else PREV_IMAGE_TAG env / deploy-state)
    --yes         skip the confirmation (non-interactive runs MUST pass it)
    service ...   default: gateway worker engine-pool web (db/valkey refused)
The DB is NEVER rolled back automatically (forward-only migrations, §4) —
manual psql / restore pointers are in this file's header.
EOF
}

app_images() { # services... → resolved image refs (one per line)
  local out
  out="$(compose config --images "$@" 2>/dev/null || true)"
  if [ -z "$out" ]; then
    out="$(compose config "$@" 2>/dev/null | sed -n 's/^ *image: *//p' | tr -d '"' || true)"
  fi
  printf '%s\n' "$out"
}

repo_of() { # image ref → repository (strip a trailing :tag, keep registry ports)
  local r="$1" t="${r##*:}"
  if [ "$t" != "$r" ] && [ "${t#*/}" = "$t" ]; then printf '%s\n' "${r%:*}"; else printf '%s\n' "$r"; fi
}

wait_healthy() { # per-container docker health gate (worker may have replicas §17.2)
  local svc="$1" waited=0 id status
  local ids; ids="$(compose ps -q "$svc" 2>/dev/null || true)"
  [ -n "$ids" ] || { err "no container found for $svc"; return 1; }
  for id in $ids; do
    waited=0
    while :; do
      status="$(docker inspect -f '{{.State.Status}}' "$id" 2>/dev/null || echo exited)"
      [ "$status" = "running" ] || { err "$svc container exited"; return 1; }
      [ "$(docker inspect -f '{{if .State.Health}}{{.State.Health.Status}}{{else}}none{{end}}' "$id" 2>/dev/null)" = "healthy" ] && break
      sleep 2
      waited=$((waited + 2))
      [ "$waited" -ge "$HEALTH_TIMEOUT" ] && { err "$svc not healthy after ${HEALTH_TIMEOUT}s"; return 1; }
    done
    ok "$svc container ${id::12} healthy (${waited}s)"
  done
}

# --- args -----------------------------------------------------------------------------
OPT_TAG=""; ASSUME_YES="${ROLLBACK_YES:-0}"; SERVICES=()
while [ $# -gt 0 ]; do
  case "$1" in
    --tag) [ $# -ge 2 ] || die "--tag needs <sha>"; OPT_TAG="$2"; shift 2 ;;
    --yes|-y) ASSUME_YES=1; shift ;;
    -h|--help) usage; exit 0 ;;
    --) shift; while [ $# -gt 0 ]; do SERVICES+=("$1"); shift; done ;;
    -*) die "unknown flag: $1 (see --help)" ;;
    *) SERVICES+=("$1"); shift ;;
  esac
done
[ "${#SERVICES[@]}" -gt 0 ] || SERVICES=(gateway worker engine-pool web)

# --- pre-flight -------------------------------------------------------------------------
[ -r "$ENV_FILE" ] || die "env file not readable: $ENV_FILE (secrets live on the box only — infra/environments.md)"
[ -r "$COMPOSE_FILE" ] || die "compose file not readable: $COMPOSE_FILE"

for svc in "${SERVICES[@]}"; do
  case "$svc" in
    db|valkey) die "refusing to roll back '$svc': the db schema is forward-only (§4) and queue state must not bounce (§17.2)" ;;
    caddy) warn "rolling back caddy (library image) — unusual; proceed carefully" ;;
  esac
done

# --- resolve the previous tag ------------------------------------------------------------
PREV="${OPT_TAG:-${PREV_IMAGE_TAG:-}}"
if [ -z "$PREV" ]; then
  [ -r "$STATE_FILE" ] || die "no --tag / PREV_IMAGE_TAG and no state file at $STATE_FILE — deploy at least once with deploy-v2.sh, or pass --tag <sha> (CI keeps app:<sha> in GHCR)"
  PREV="$(grep -m1 -E '^IMAGE_TAG_PREVIOUS=' "$STATE_FILE" | cut -d= -f2- || true)"
  [ -n "$PREV" ] || die "state file has no IMAGE_TAG_PREVIOUS — pass --tag <sha> (the box keeps the previous two images, §17.3)"
fi
STATE_CUR=""
if [ -r "$STATE_FILE" ]; then
  STATE_CUR="$(grep -m1 -E '^IMAGE_TAG_CURRENT=' "$STATE_FILE" | cut -d= -f2- || true)"
fi

# --- the DB warning — always, before anything is touched (§4 forward-only) -----------------
warn "the DATABASE is NOT rolled back by this script (forward-only migrations, §4)."
warn "  if the failed deploy migrated, old code runs against the newer schema for one"
warn "  deploy window (§17.3). Manual psql / restore pointers: this file's header."
step "previous tag: $PREV${STATE_CUR:+ (current: $STATE_CUR)}"

if [ "$ASSUME_YES" != "1" ]; then
  if [ -t 0 ]; then
    read -r -p "roll back [${SERVICES[*]}] to ${PREV}? [y/N] " reply || true
    case "${reply:-}" in
      y|Y|yes|YES) ;;
      *) die "aborted (nothing was touched)" ;;
    esac
  else
    die "non-interactive shell — pass --yes (or set ROLLBACK_YES=1)"
  fi
fi

# --- repin images: docker tag <repo>:<prev> over the current reference ---------------------
step "repinning app images to :${PREV} (tag scheme app:<sha>, §17.3)"
for svc in "${SERVICES[@]}"; do
  ref="$(app_images "$svc" | awk 'NR==1')"
  if [ -z "$ref" ]; then
    err "$svc: no image reference resolved — on-box builds roll back via code:"
    err "    git checkout <last-good> && BUILD_ON_BOX=1 infra/scripts/deploy-v2.sh --build $svc"
    exit 2
  fi
  repo="$(repo_of "$ref")"
  if docker image inspect "$repo:$PREV" >/dev/null 2>&1; then
    ok "$svc: $repo:$PREV already on the box (kept tag, §17.3)"
  else
    step "$svc: pulling $repo:$PREV"
    if ! docker pull "$repo:$PREV"; then
      err "$svc: $repo:$PREV not found locally or in the registry"
      err "    the box keeps the previous TWO images (§17.3) — verify the tag with:"
      err "    $STATE_FILE · $HISTORY_FILE · docker images | grep $repo"
      exit 2
    fi
  fi
  docker tag "$repo:$PREV" "$ref" \
    || { err "$svc: docker tag $repo:$PREV → $ref failed"; exit 2; }
  ok "$svc: $ref ← $repo:$PREV"
done

# --- up + health gate -------------------------------------------------------------------------
step "docker compose up -d --no-deps ${SERVICES[*]}"
compose up -d --no-deps "${SERVICES[@]}"
ok "recreated on $PREV"

step "health gate (≤ ${HEALTH_TIMEOUT}s per service, §17.3)"
for svc in "${SERVICES[@]}"; do
  if ! wait_healthy "$svc"; then
    err "rollback did NOT restore health for $svc — treat as a §17.4 incident (RB-01/RB-03)"
    err "the DB was untouched by this script (forward-only, §4)"
    exit 3
  fi
done

step "post-rollback smoke"
if ! "$SCRIPT_DIR/smoke.sh"; then
  err "smoke still failing after rollback — §17.4 incident; start with the failed check names above"
  exit 3
fi
ok "smoke green on $PREV"

# --- state bookkeeping ---------------------------------------------------------------------------
if [ -r "$STATE_FILE" ] && [ -n "$STATE_CUR" ]; then
  {
    echo "# rewritten by rollback.sh at $(date -u +%FT%TZ)"
    echo "IMAGE_TAG_CURRENT=$PREV"
    echo "IMAGE_TAG_PREVIOUS=$STATE_CUR"
    grep -E '^DEPLOYED_AT=' "$STATE_FILE" || true
  } > "${STATE_FILE}.tmp"
  mv "${STATE_FILE}.tmp" "$STATE_FILE"
  printf '%s rollback %s (from %s)\n' "$(date -u +%FT%TZ)" "$PREV" "$STATE_CUR" >> "$HISTORY_FILE" || true
  ok "state updated: current=$PREV previous=$STATE_CUR"
fi

step "ROLLBACK COMPLETE → $PREV"
warn "DB untouched (forward-only, §4). If the failed deploy left migrations applied, verify the old code tolerates the new schema for one deploy window (§17.3)."
