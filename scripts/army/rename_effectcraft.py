#!/usr/bin/env python3
"""scripts/army/rename_effectcraft.py — round-13 C1-C10 de-effectcraft rename.

Implements w1-a18's RENAME blast-radius map. Idempotent: safe to re-run.

Order (per the map):
  R1  crate names + underscore identifiers  (effectcraft-*  -> studio-*, effectcraft_x -> studio_x)
  R2  JS bridge globals                     (window.effectcraft -> window.studioEngine, effectcraftLoad -> studioEngineLoad,
                                             effectcraft_canvas -> studio_canvas, effectcraftModule -> studioEngineModule)
  R3  dist filenames + refs                 (effectcraft_web* -> studio_web*; caddy/dev-ready/next.config)
  R4  storage names in host.js              ("effectcraft" OPFS/IDB -> "studio" — migration handled by hand in host.js)
  R5  SW cache prefix + cleanup             (effectcraft-<v> -> studio-<v>, delete BOTH on activate)
  R6  env vars                              (EFFECTCRAFT_CLI_PATH -> STUDIO_ENGINE_CLI_PATH; read-fallback added by hand)
  R7  demo/brand strings                    (hero layer "EFFECTCRAFT" -> "STUDIO", WebM MuxingApp/WritingApp, app.version)
  R8  log target default                    (RUST_LOG warn,effectcraft=info -> warn,studio=info)

SKIPS (license/pin obligations, per w1-a17 license audit + army reports):
  editor/UPSTREAM.md, editor/NOTICE, editor/patches/, editor/docs/brand/LICENSE-brand.txt,
  *.attribution, ATTRIBUTION*, licenses, .git, target/, node_modules/, army/ (historical audit
  artifacts), apps/web/public/editor/ (committed dist — regenerated by the build), docs/images
  (deleted by the leftover purge).
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path("/home/z/my-project")
EDITOR = ROOT / "editor"

SKIP_PATH_PARTS = (
    "/.git/", "/target/", "/node_modules/", "/army/", "/.local/",
    "apps/web/public/editor/",  # committed dist — regenerated
    "editor/patches/",
    "editor/docs/brand/",
    "editor/docs/images/",
)
SKIP_FILE_SUFFIX = (".attribution", ".lock", ".png", ".ico", ".icns", ".svg", ".jpg", ".webp", ".wasm", ".gz", ".tgz")
SKIP_FILE_NAMES = {"UPSTREAM.md", "NOTICE", "LICENSE-MIT", "LICENSE-APACHE", "Cargo.lock"}

# Files allowed to keep historical references (compliance/history):
COMPLIANCE_ALLOW = re.compile(
    r"(UPSTREAM\.md|NOTICE|ATTRIBUTION|LICENSE|\.attribution$|patches/|docs/brand/|CONTRIBUTING\.md$|contributors/)"
)


def iter_files(roots: list[Path], text_suffixes) -> list[Path]:
    out: list[Path] = []
    for root in roots:
        for p in root.rglob("*"):
            if not p.is_file():
                continue
            s = str(p)
            if any(part in s for part in SKIP_PATH_PARTS):
                continue
            if p.name in SKIP_FILE_NAMES or p.suffix in SKIP_FILE_SUFFIX:
                continue
            if COMPLIANCE_ALLOW.search(s):
                continue
            if text_suffixes and p.suffix not in text_suffixes:
                continue
            out.append(p)
    return out


def sub_file(path: Path, pattern: str, repl: str, count: int = 0) -> int:
    """Apply re.sub to a file; returns number of replacements. count>0 limits."""
    try:
        text = path.read_text(encoding="utf-8")
    except (UnicodeDecodeError, IsADirectoryError):
        return 0
    new, n = re.subn(pattern, repl, text, count=count)
    if n and new != text:
        path.write_text(new, encoding="utf-8")
    return n


def git(*args: str) -> str:
    return subprocess.run(["git", "-C", str(ROOT), *args], capture_output=True, text=True).stdout


def main() -> None:
    total = 0

    # ── R0: directory renames (git mv so history follows)
    for old, new in [("editor/apps/effectcraft-web", "editor/apps/studio-web"),
                     ("editor/apps/effectcraft-cli", "editor/apps/studio-cli")]:
        if (ROOT / old).is_dir() and not (ROOT / new).is_dir():
            subprocess.run(["git", "-C", str(ROOT), "mv", old, new], check=True)
            print(f"[R0] git mv {old} -> {new}")

    # text file universes
    rust_files = iter_files([EDITOR], {".rs", ".toml"})
    web_files = iter_files([ROOT / "apps/web/src", ROOT / "packages", ROOT / "services", ROOT / "scripts",
                            ROOT / "infra", ROOT / ".github", ROOT / "tests"], {".ts", ".tsx", ".js", ".mjs", ".cjs",
                                                                                ".json", ".md", ".yml", ".yaml", ".html"})
    editor_web_assets = iter_files([EDITOR / "apps"], {".js", ".html", ".webmanifest", ".rs", ".mjs", ".md", ".toml"})

    # ── R1: crate names + underscore identifiers (Rust workspace + build tooling)
    n = 0
    for p in rust_files + editor_web_assets:
        n += sub_file(p, r"\beffectcraft-([a-z0-9-]+)\b", r"studio-\1")   # hyphen crate names (Cargo.toml, docs)
        n += sub_file(p, r"\beffectcraft_([a-z0-9_]+)\b", r"studio_\1")   # underscore identifiers (use paths)
    # repo-level references to the editor crates (CI, root scripts)
    for p in web_files:
        n += sub_file(p, r"\beffectcraft-(web|cli|engine|ui-egui|effects|host)\b", r"studio-\1")
    print(f"[R1] crate identifiers: {n} replacements")
    total += n

    # ── R2: JS bridge globals
    n = 0
    for p in editor_web_assets + web_files:
        n += sub_file(p, r"\bwindow\.effectcraftLoad\b", "window.studioEngineLoad")
        n += sub_file(p, r"\bwindow\.effectcraftModule\b", "window.studioEngineModule")
        n += sub_file(p, r"\bwindow\.effectcraft\b", "window.studioEngine")
        n += sub_file(p, r"\beffectcraftLoad\b", "studioEngineLoad")
        n += sub_file(p, r"\beffectcraft_canvas\b", "studio_canvas")
        n += sub_file(p, r"\bEffectcraft(\w)", r"StudioEngine\1")  # TS type names EffectcraftBridge etc.
    print(f"[R2] bridge globals: {n} replacements")
    total += n

    # ── R3: dist filenames
    n = 0
    for p in editor_web_assets + web_files + [ROOT / "infra/caddy/Caddyfile"]:
        if not p.exists():
            continue
        n += sub_file(p, r"\beffectcraft_web_bg\.wasm\b", "studio_web_bg.wasm")
        n += sub_file(p, r"\beffectcraft_web_opt\.wasm\b", "studio_web_opt.wasm")
        n += sub_file(p, r"\beffectcraft_web\.js\b", "studio_web.js")
        n += sub_file(p, r"\beffectcraft_web\.wasm\b", "studio_web.wasm")
    print(f"[R3] dist filenames: {n} replacements")
    total += n

    # ── R4: storage names (host.js DIR/DB + cache/handles/output)
    host_js = EDITOR / "apps/studio-web/js/host.js"
    if host_js.exists():
        n = 0
        n += sub_file(host_js, r'const DIR = "effectcraft";', 'const DIR = "studio";')
        n += sub_file(host_js, r'const DB = "effectcraft";', 'const DB = "studio";')
        n += sub_file(host_js, r'"effectcraft-cache"', '"studio-cache"')
        n += sub_file(host_js, r'"effectcraft-handles"', '"studio-handles"')
        n += sub_file(host_js, r'"effectcraft-output"', '"studio-output"')
        print(f"[R4] host.js storage names: {n} replacements")
        total += n

    # ── R5: SW cache prefix + both-prefix cleanup
    sw_js = EDITOR / "apps/studio-web/web/sw.js"
    if sw_js.exists():
        n = 0
        n += sub_file(sw_js, r"const CACHE = `effectcraft-\$\{VERSION\}`;", "const CACHE = `studio-${VERSION}`;")
        n += sub_file(sw_js, r'k\.startsWith\("effectcraft-"\) && k !== CACHE', '(k.startsWith("effectcraft-") || k.startsWith("studio-")) && k !== CACHE')
        print(f"[R5] sw.js cache prefix: {n} replacements")
        total += n

    # ── R6: env vars
    n = 0
    for p in web_files + editor_web_assets:
        n += sub_file(p, r"\bEFFECTCRAFT_CLI_PATH\b", "STUDIO_ENGINE_CLI_PATH")
        n += sub_file(p, r"\bEFFECTCRAFT_CONFIG_DIR\b", "STUDIO_ENGINE_CONFIG_DIR")
        n += sub_file(p, r"\bEFFECTCRAFT_CONTROL_PORT\b", "STUDIO_ENGINE_CONTROL_PORT")
    print(f"[R6] env vars: {n} replacements")
    total += n

    # ── R7: demo/brand strings (atomic set: demo.rs + engine tests + ui_agent_audit + bench)
    demo_files = [
        EDITOR / "crates/engine/src/demo.rs",
        EDITOR / "crates/engine/src/tests.rs",
        EDITOR / "crates/ui-egui/src/automation/ui_agent_audit.rs",
        EDITOR / "xtask/src/bench.rs",
    ]
    n = 0
    for p in demo_files:
        if p.exists():
            n += sub_file(p, r'"EFFECTCRAFT"', '"STUDIO"')
            n += sub_file(p, r"EffectCraft Intro", "Studio Intro")
    # WebM writer identity + render log header + lottie generator + automation serverInfo
    for p in [EDITOR / "crates/export/src/webm.rs", EDITOR / "crates/export/src/webm_av1.rs",
              EDITOR / "crates/export/src/pipeline.rs", EDITOR / "crates/lottie/src/export.rs",
              EDITOR / "crates/automation/src/lib.rs", EDITOR / "crates/automation/src/model.rs"]:
        if not p.exists():
            continue
        n += sub_file(p, r'"EffectCraft"', '"Studio"')
        n += sub_file(p, r"effectcraft://", "studio://")
    print(f"[R7] demo/brand strings: {n} replacements")
    total += n

    # ── R8: RUST_LOG default
    n = 0
    for p in rust_files:
        n += sub_file(p, r"warn,effectcraft=info", "warn,studio=info")
    print(f"[R8] RUST_LOG default: {n} replacements")
    total += n

    print(f"TOTAL: {total} replacements")
    if total == 0:
        print("NOTE: zero replacements — rename already applied?")


if __name__ == "__main__":
    sys.exit(main())
